(** A {!Plan.t} as OCaml source. Serialization is left to ppx_yojson_conv. *)

let rec ty : Plan.ty -> string = function
  | Scalar String -> "string"
  | Scalar Int -> "int"
  | Scalar Float -> "float"
  | Scalar Bool -> "bool"
  | Scalar Timestamp -> "Aws_json_wire.timestamp"
  | Scalar Blob -> "Aws_json_wire.blob"
  | Scalar Document -> "Aws_json_wire.document"
  | Scalar Unit -> "Aws_json_wire.empty"
  | Named name -> (name :> string)
  | List t -> ty t ^ " list"
  | Map t -> ty t ^ " Aws_json_wire.map"

(** [[ `STRING | `STRING_LIST | `Unknown_value of string ]], tagged by member name. Smithy enums are
    open: a value the model does not know decodes to [`Unknown_value]. *)
let enum ({ name; values } : Plan.enum) =
  let name = (name :> string) in
  let values =
    Nel.to_list values |> List.map @@ fun ((tag : Naming.Tag.t), v) -> (tag :> string), v
  in
  Printf.sprintf
    {|type %s = [ %s | `Unknown_value of string ]

let yojson_of_%s : %s -> Yojson.Safe.t = function
%s  | `Unknown_value s -> `String s

let %s_of_yojson : Yojson.Safe.t -> %s = function
%s  | `String s -> `Unknown_value s
  | json -> Ppx_yojson_conv_lib.Yojson_conv.of_yojson_error "%s: string expected" json|}
    name
    (values |> List.map (fun (tag, _) -> "`" ^ tag) |> String.concat " | ")
    name name
    (values
    |> List.map (fun (tag, v) -> Printf.sprintf "  | `%s -> `String %S\n" tag v)
    |> String.concat "")
    name name
    (values
    |> List.map (fun (tag, v) -> Printf.sprintf "  | `String %S -> `%s\n" v tag)
    |> String.concat "")
    name

let field ({ wire; name; ty = t; required } : Plan.field) =
  if required then
    Printf.sprintf "%s : %s; [@key %S]" (name :> string) (ty t) wire
  else
    Printf.sprintf "%s : %s option; [@key %S] [@yojson.option]" (name :> string) (ty t) wire

let record ({ name; fields; _ } : Plan.record) =
  match fields with
  | [] -> Printf.sprintf "%s = Aws_json_wire.empty" (name :> string)
  | fields ->
    Printf.sprintf "%s = {\n  %s\n}\n[@@yojson.allow_extra_fields]"
      (name :> string)
      (fields |> List.map field |> String.concat "\n  ")

(** [let get_item_input ~table_name ~key ?consistent_read () = { ... }]: callers name only what they
    set. *)
let constructor ({ name; fields; constructor } : Plan.record) =
  if not constructor then
    None
  else
    let arg ({ name; required; _ } : Plan.field) =
      (if required then "~" else "?") ^ (name :> string)
    in
    let unit = if List.for_all (fun (f : Plan.field) -> f.required) fields then "" else " ()" in
    Some
      (Printf.sprintf "let %s %s%s : %s = { %s }"
         (name :> string)
         (fields |> List.map arg |> String.concat " ")
         unit
         (name :> string)
         (fields |> List.map (fun (f : Plan.field) -> (f.name :> string)) |> String.concat "; "))

let operation ({ name; action; input; output } : Plan.operation) =
  Printf.sprintf
    {|module %s = struct
  module Def = struct
    let action = %S

    type request = %s [@@deriving yojson_of]
    type response = %s [@@deriving of_yojson]
  end

  include Def
  include Aws_json_transport.Make (Def)
end|}
    (Naming.Ident.module_name name) action (ty input) (ty output)

(** The whole generated module; [source] is the model file it comes from. *)
let run ~source ({ service; enums; records; operations } : Plan.t) =
  Printf.sprintf
    {|(* Generated by smithy/smithy_gen.exe from %s. Do not edit. *)

open Ppx_yojson_conv_lib.Yojson_conv.Primitives

module Error = Aws_json_error
module Wire = Aws_json_wire
module Transport = Aws_json_transport

type t = Transport.t

let protocol =
  Transport.{ version = %s; target_prefix = %S; signing_name = %S; endpoint_prefix = %S }

let make ?endpoint ?provider ~region ~now () = Transport.make ?endpoint ?provider ~protocol ~region ~now ()

%s

type %s
[@@deriving yojson]

%s

%s
|}
    source
    (match service.protocol with Json_1_0 -> "Json_1_0" | Json_1_1 -> "Json_1_1")
    service.target_prefix
    (service.signing_name :> string)
    (service.endpoint_prefix :> string)
    (enums |> List.map enum |> String.concat "\n\n")
    (records |> List.map record |> String.concat "\n\nand ")
    (records |> List.filter_map constructor |> String.concat "\n")
    (operations |> List.map operation |> String.concat "\n\n")
